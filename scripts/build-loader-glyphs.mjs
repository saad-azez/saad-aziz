// Bakes the loader's count (0-9 in Aminute, % in Manrope) into outlines, so the
// count is on screen from the very first frame: no font to wait for, in a worker
// that has no document to load one into.
//   node scripts/build-loader-glyphs.mjs
import fs from 'node:fs';
import opentype from 'opentype.js';

const load = file => { const b = fs.readFileSync(file); return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)); };
const outline = (font, char) => {
  const glyph = font.charToGlyph(char);
  return { d: glyph.getPath(0, 0, 1000).toPathData(0), advance: Math.round(glyph.advanceWidth / font.unitsPerEm * 1000) };
};
const display = load('public/fonts/aminute.woff');
const body = load('public/fonts/manrope.ttf');
const digits = [...'0123456789'].map(c => outline(display, c));
const percent = outline(body, '%');
const source = `// Generated by scripts/build-loader-glyphs.mjs: outlines at 1000 units to the em, y down, baseline at 0.
export const DIGITS = ${JSON.stringify(digits)};
export const PERCENT = ${JSON.stringify(percent)};
`;
fs.writeFileSync('src/components/loader/glyphs.js', source);
console.log('glyphs.js', source.length, 'bytes');
