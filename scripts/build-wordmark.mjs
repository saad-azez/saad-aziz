/**
 * Read the OpenType font and emit Three.js contours plus per-letter metrics.
 * npm run font rebuilds the OTF from the editable logo glyph source first.
 * npm run wordmark regenerates browser data after editing the OTF directly.
 * Existing WORDMARK / WORDMARK_FONT overrides remain available.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import opentype from 'opentype.js';

const here = dirname(fileURLToPath(import.meta.url));

const WORD = process.env.WORDMARK ?? 'SAADi';
const SOURCE = process.env.WORDMARK_FONT ? resolve(here, '../assets/fonts', process.env.WORDMARK_FONT) : resolve(here, '../public/fonts/SAADiDisplay-Regular.otf');
const OUTPUT = resolve(here, '../src/webgl/hero/wordmark.paths.js');

/** Glyphs are emitted at this em size; the hero scales from there. */
const CAP = 70;

const bytes = readFileSync(SOURCE);
const font = opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
const EM = 100 * CAP / capHeight(font, 100);
const scale = EM / font.unitsPerEm;

/** A face's cap height, measured off its H. */
function capHeight(face, em) {
  if (face.tables.os2.sCapHeight) return face.tables.os2.sCapHeight * em / face.unitsPerEm;
  const box = face.charToGlyph('H').getPath(0, 0, em).getBoundingBox();
  return box.y2 - box.y1;
}

/** One glyph, drawn from its own origin so the hero can place letters singly. */
function cut(char) {
  const fontChar = char;
  const glyph = font.charToGlyph(fontChar);
  const path = glyph.getPath(0, 0, EM);
  return {
    char, fontChar,
    path: path.toPathData(3),
    advance: +(glyph.advanceWidth * scale).toFixed(3),
  };
}

const letters = [...WORD].map(cut);

// The kerning for each adjacent pair, as the face sets it.
const kern = {};
for (let i = 0; i < letters.length - 1; i += 1) {
  const left = letters[i].char;
  const right = letters[i + 1].char;
  const value = font.getKerningValue(font.charToGlyph(letters[i].fontChar), font.charToGlyph(letters[i + 1].fontChar)) * scale;
  if (value) kern[left + right] = +value.toFixed(3);
}

let cursor = 0;
letters.forEach((letter, i) => {
  letter.origin = +cursor.toFixed(3);
  cursor += letter.advance + (kern[letter.char + letters[i + 1]?.char] ?? 0);
});

const file = `/**
 * Generated by \`npm run wordmark\` — do not edit by hand.
 *
 * ${font.names.fontFamily?.en ?? font.names.windows?.fontFamily?.en ?? 'display face'} · "${WORD}" · em ${EM}
 *
 * The word's glyphs, each drawn from its own origin. \`advance\` and
 * \`kern\` are the face's own metrics, so the word sets exactly as the type
 * designer intended.
 */
export const WORDMARK = ${JSON.stringify({ fontSize: EM, capHeight: +capHeight(font, EM).toFixed(3), letters, kern }, null, 2)};
`;

mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(OUTPUT, file);

console.log(`${WORD} → ${OUTPUT.replace(resolve(here, '..'), '.')} (${(file.length / 1024).toFixed(1)}KB)`);
letters.forEach(({ char, advance, path }) => console.log(
  `  ${char}  advance ${advance.toFixed(1)}  path ${path.length}b`,
));
console.log(`  kern pairs: ${Object.keys(kern).length ? Object.entries(kern).map(([k, v]) => `${k} ${v}`).join(', ') : 'none'}`);

// Three.js consumes the same OpenType contours, without a runtime OTF parser.
const glyphs = {};
for (const char of [...new Set([...letters.map(l => l.fontChar), 'a', ' '])]) {
  const glyph = font.charToGlyph(char), outline = [];
  let start;
  for (const c of glyph.path.commands) {
    if (c.type === 'M') { outline.push('m', c.x, c.y); start = c; }
    if (c.type === 'L') outline.push('l', c.x, c.y);
    if (c.type === 'Q') outline.push('q', c.x, c.y, c.x1, c.y1);
    if (c.type === 'C') outline.push('b', c.x, c.y, c.x1, c.y1, c.x2, c.y2);
    if (c.type === 'Z' && start) outline.push('l', start.x, start.y);
  }
  glyphs[char] = { ha: glyph.advanceWidth, o: outline.join(' ') };
}
writeFileSync(resolve(here, '../src/webgl/hero/saadi.typeface.json'), JSON.stringify({
  familyName: font.names.fontFamily?.en ?? font.names.windows?.fontFamily?.en ?? 'SAADi Display', resolution: font.unitsPerEm,
  ascender: font.ascender, descender: font.descender,
  boundingBox: { yMin: font.descender, yMax: font.ascender }, underlineThickness: 50, glyphs,
}));
